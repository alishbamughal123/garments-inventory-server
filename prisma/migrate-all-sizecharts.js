const getSingleSizeSpecs = (sizeKey, chart) => {
  if (!sizeKey) return null;
  const s = String(sizeKey).trim().toUpperCase();
  const matchedSize = chart.sizes.find(
    (sz) => sz.key.toUpperCase() === s || sz.label.toUpperCase().includes(s)
  ) || chart.sizes[0];

  const breakdown = {};
  chart.measurements.forEach((m) => {
    breakdown[m.code] = {
      name: m.name,
      norwegianName: m.norwegianName,
      value: m.values[matchedSize.key] || "—",
      tolerance: m.tolerance,
    };
  });

  return {
    size: matchedSize.label,
    sizeKey: matchedSize.key,
    colorBadge: matchedSize.colorBadge || "standard",
    colorHex: matchedSize.colorHex || "#3b82f6",
    unit: chart.unit,
    measurements: breakdown,
  };
};

async function main() {
  console.log("=== SEEDING ALL SIZE CHARTS (20110, 20111, 200120-200127) ===");

  for (const item of ALL_CHARTS) {
    for (const styleNo of item.styles) {
      const id = `sizechart-${styleNo}`;
      const applicableStylesJson = JSON.stringify(item.chart.applicableStyles);
      const sizesJson = JSON.stringify(item.chart.sizes);
      const measurementsJson = JSON.stringify(item.chart.measurements);

      await prisma.$executeRawUnsafe(`
        INSERT INTO "SizeChart" ("id", "styleNumber", "title", "applicableStyles", "sizes", "measurements", "unit", "updatedAt")
        VALUES ($1, $2, $3, $4::jsonb, $5::jsonb, $6::jsonb, 'cm', CURRENT_TIMESTAMP)
        ON CONFLICT ("styleNumber") DO UPDATE SET
          "title" = EXCLUDED."title",
          "applicableStyles" = EXCLUDED."applicableStyles",
          "sizes" = EXCLUDED."sizes",
          "measurements" = EXCLUDED."measurements",
          "unit" = EXCLUDED."unit",
          "updatedAt" = CURRENT_TIMESTAMP;
      `, id, styleNo, `Size Chart for Article ${styleNo}`, applicableStylesJson, sizesJson, measurementsJson);

      console.log(`-> Ensured SizeChart in DB for Style #${styleNo}`);

      // Update products
      const products = await prisma.product.findMany({
        where: {
          OR: [
            { baseStyleNumber: styleNo },
            { styleNumber: { startsWith: styleNo } },
            { sku: { startsWith: styleNo } },
          ],
        },
      });

      for (const prod of products) {
        const singleSpec = getSingleSizeSpecs(prod.size, item.chart);
        const chartJson = JSON.stringify(item.chart);
        const singleSpecJson = JSON.stringify(singleSpec);

        await prisma.$executeRawUnsafe(`
          UPDATE "Product"
          SET "sizeChart" = $1::jsonb,
              "sizeChartMeasurements" = $2::jsonb,
              "updatedAt" = CURRENT_TIMESTAMP
          WHERE "id" = $3;
        `, chartJson, singleSpecJson, prod.id);
      }
      console.log(`   Updated ${products.length} product variants for style ${styleNo}`);
    }
  }

  console.log("=== ALL SIZE CHARTS MIGRATED SUCCESSFULLY! ===");
}

if (require.main === module) {
  main()
    .then(async () => {
      await prisma.$disconnect();
      process.exit(0);
    })
    .catch(async (e) => {
      console.error("Migration error:", e);
      await prisma.$disconnect();
      process.exit(1);
    });
}

